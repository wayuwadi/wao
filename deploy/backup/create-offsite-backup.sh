#!/usr/bin/env bash
set -Eeuo pipefail

config_dir="${WAO_BACKUP_CONFIG_DIR:-/etc/wao-backup}"
webdav_config="${config_dir}/webdav.env"
passphrase_file="${config_dir}/encryption-passphrase"
project_root="${WAO_BACKUP_PROJECT_ROOT:-}"
if [[ -z "$project_root" && -f /etc/systemd/system/jenkins.service.d/override.conf ]]; then
  project_root="$(sed -n 's/^Environment="WAO_MASTER_PROJECT_ROOT=\(.*\)"$/\1/p' \
    /etc/systemd/system/jenkins.service.d/override.conf | tail -n 1)"
fi
project_root="${project_root:-/home/wadi/Desktop/deploy/wao}"
jumpserver_root="${WAO_BACKUP_JUMPSERVER_ROOT:-/opt/wao-jumpserver}"
jenkins_backup_dir="${WAO_BACKUP_JENKINS_BACKUP_DIR:-/var/backups/jenkins}"
local_root="${WAO_BACKUP_LOCAL_DIR:-/var/backups/wao-offsite}"
webdav_client="${WAO_BACKUP_WEBDAV_CLIENT:-/usr/local/lib/wao-backup/webdav_client.py}"
node_name="${WAO_BACKUP_NODE_NAME:-linux2}"
local_retention_days="${WAO_BACKUP_LOCAL_RETENTION_DAYS:-7}"
remote_retention_days="${WAO_BACKUP_REMOTE_RETENTION_DAYS:-30}"
chunk_bytes="${WAO_BACKUP_CHUNK_BYTES:-1073741824}"

if [[ "${WAO_BACKUP_TEST_MODE:-false}" != true && "$(id -u)" -ne 0 ]]; then
  echo 'The offsite backup must run as root.' >&2
  exit 1
fi

for value in "$local_retention_days" "$remote_retention_days" "$chunk_bytes"; do
  [[ "$value" =~ ^[0-9]+$ ]] || { echo "Invalid numeric backup setting: $value" >&2; exit 2; }
done
(( local_retention_days >= 1 && remote_retention_days >= 1 && chunk_bytes >= 1048576 )) || {
  echo 'Backup retention or chunk size is below the safe minimum.' >&2
  exit 2
}
for safe_root in "$project_root" "$jumpserver_root" "$jenkins_backup_dir" "$local_root"; do
  [[ "$safe_root" == /* && "$safe_root" != / ]] || {
    echo "Backup path must be a safe absolute directory: $safe_root" >&2
    exit 2
  }
done

for required in "$webdav_config" "$passphrase_file" "$project_root/deploy/.env" "$webdav_client"; do
  [[ -f "$required" ]] || { echo "Required backup input is missing: $required" >&2; exit 1; }
done
[[ -d "$jumpserver_root/config" && -d "$jumpserver_root/data" ]] || {
  echo "JumpServer persistent data is missing below $jumpserver_root" >&2
  exit 1
}

umask 077
install -d -m 0700 "$local_root"
lock_file="$local_root/.backup.lock"
exec 9>"$lock_file"
flock -n 9 || { echo 'Another offsite backup is already running.' >&2; exit 0; }

stamp="$(date -u +%Y%m%dT%H%M%SZ)"
snapshot_dir="$local_root/$stamp"
staging_dir="$(mktemp -d "$local_root/.staging-${stamp}.XXXXXX")"
jumpserver_stopped=false
cleanup() {
  status=$?
  trap - EXIT HUP INT TERM
  if [[ "$jumpserver_stopped" == true ]]; then
    start_jumpserver || true
  fi
  rm -rf -- "$staging_dir"
  if (( status != 0 )) && [[ -d "$snapshot_dir" && ! -f "$snapshot_dir/manifest.json" ]]; then
    rm -rf -- "$snapshot_dir"
  fi
  exit "$status"
}
trap cleanup EXIT HUP INT TERM

start_jumpserver() {
  if [[ "${WAO_BACKUP_SKIP_JUMPSERVER_CONTROL:-false}" == true ]]; then
    jumpserver_stopped=false
    return
  fi
  JS_CONFIG_DIR="$jumpserver_root/config" UNCHECK_DEPENDENCIES=1 \
    bash "$jumpserver_installer/jmsctl.sh" start --skip-kotl
  for attempt in $(seq 1 30); do
    if curl --fail --silent --show-error --max-time 10 \
      http://127.0.0.1:18080/api/health/ >/dev/null; then
      jumpserver_stopped=false
      return
    fi
    [[ "$attempt" -lt 30 ]] && sleep 10
  done
  echo 'JumpServer did not recover after the backup snapshot.' >&2
  return 1
}

set -a
# This file is generated by the repository and contains shell-safe values.
# shellcheck disable=SC1090
. "$project_root/deploy/.env"
set +a
: "${DB_ROOT_PASS:?DB_ROOT_PASS is required in deploy/.env}"
: "${DB_NAME:?DB_NAME is required in deploy/.env}"
if [[ "${WAO_STORAGE_MODE:-mysql}" == s3 ]]; then
  asset_lock="${WAO_IMAGE_BACKUP_LOCK_FILE:-/run/lock/wao-image-backup.lock}"
  exec 8>"$asset_lock"
  flock -w 7200 8 || {
    echo 'Timed out waiting for image maintenance before object backup.' >&2
    exit 1
  }
  source_check=/usr/local/lib/wao-backup/verify-backup-source.py
  [[ -f "$source_check" ]] || {
    echo 'WAO backup source verifier is missing.' >&2
    exit 1
  }
  python3 "$source_check" >/dev/null || {
    echo 'WAO return replica is not verified; refusing an inconsistent object recovery archive.' >&2
    exit 1
  }
fi

if [[ "${WAO_BACKUP_SKIP_JENKINS_REFRESH:-false}" != true ]]; then
  /usr/local/lib/wao-jenkins/backup-controller.sh --require-created
fi
jenkins_archive="$(find "$jenkins_backup_dir" -maxdepth 1 -type f -name 'jenkins-home-*.tar.gz' -mmin -1560 -printf '%T@ %p\n' | sort -nr | awk 'NR == 1 {print $2}')"
[[ -n "$jenkins_archive" && -f "$jenkins_archive.sha256" ]] || {
  echo 'No verified Jenkins backup newer than 26 hours is available.' >&2
  exit 1
}
(cd "$jenkins_backup_dir" && sha256sum -c "$(basename "$jenkins_archive.sha256")")

mkdir -p "$staging_dir/recovery/database" "$staging_dir/recovery/jenkins"
cp -p "$jenkins_archive" "$jenkins_archive.sha256" "$staging_dir/recovery/jenkins/"

mysql_config="$staging_dir/mysql-client.cnf"
dump_host="${MYSQL_HOST:-127.0.0.1}"
[[ "$dump_host" == host.docker.internal ]] && dump_host=127.0.0.1
cat >"$mysql_config" <<EOF
[client]
user=root
password=$DB_ROOT_PASS
host=$dump_host
port=${MYSQL_PORT:-3306}
EOF

database_dump="$staging_dir/recovery/database/${DB_NAME}.sql.gz"
dump_fifo="$staging_dir/mysql-dump.fifo"
mkfifo "$dump_fifo"
gzip -9 <"$dump_fifo" >"$database_dump" &
gzip_pid=$!
dump_arguments=(
  "--defaults-extra-file=$mysql_config"
  --single-transaction
  --set-gtid-purged=OFF
  --routines
  --events
  --hex-blob
  "$DB_NAME"
)
run_mysql_dump() {
  if [[ -n "${WAO_BACKUP_MYSQLDUMP_COMMAND:-}" ]]; then
    "$WAO_BACKUP_MYSQLDUMP_COMMAND" "${dump_arguments[@]}"
  elif command -v mysqldump >/dev/null 2>&1; then
    mysqldump "${dump_arguments[@]}"
  else
    docker run --rm --network host \
      -v "$mysql_config:/run/secrets/mysql-client.cnf:ro" \
      mysql:9.7.0 mysqldump \
      --defaults-extra-file=/run/secrets/mysql-client.cnf \
      "${dump_arguments[@]:1}"
  fi
}
if ! run_mysql_dump >"$dump_fifo"; then
  kill "$gzip_pid" 2>/dev/null || true
  wait "$gzip_pid" 2>/dev/null || true
  echo 'WAO MySQL logical dump failed.' >&2
  exit 1
fi
wait "$gzip_pid"
rm -f "$dump_fifo" "$mysql_config"
gzip -t "$database_dump"

if [[ "${WAO_STORAGE_MODE:-mysql}" == s3 ]]; then
  storage_python=/usr/local/lib/wao-backup/.venv/bin/python
  [[ -x "$storage_python" && -f /usr/local/lib/wao-backup/export_object_backup.py ]] || {
    echo 'Object storage backup runtime is missing; refusing an incomplete recovery archive.' >&2
    exit 1
  }
  "$storage_python" /usr/local/lib/wao-backup/export_object_backup.py \
    "$staging_dir/recovery/objects"
fi

if [[ "${WAO_BACKUP_SKIP_JUMPSERVER_CONTROL:-false}" != true ]]; then
  jumpserver_installer="$(find "$jumpserver_root" -maxdepth 1 -type d -name 'installer-*' | sort -V | tail -n 1)"
  [[ -x "$jumpserver_installer/jmsctl.sh" ]] || {
    echo 'JumpServer control script is unavailable.' >&2
    exit 1
  }
  JS_CONFIG_DIR="$jumpserver_root/config" UNCHECK_DEPENDENCIES=1 \
    bash "$jumpserver_installer/jmsctl.sh" stop
  jumpserver_stopped=true
fi

mkdir -p "$snapshot_dir"
archive_prefix="$snapshot_dir/wao-linux2-${stamp}.tar.gz.gpg.part-"
tar \
  --exclude="${project_root#/}/deploy/backups" \
  --exclude="${project_root#/}/deploy/.public-ip" \
  -C "$staging_dir" recovery \
  -C / "${jumpserver_root#/}/config" "${jumpserver_root#/}/data" \
  -C / "${project_root#/}/deploy" \
  -czf - \
  | gpg --batch --yes --pinentry-mode loopback \
      --passphrase-file "$passphrase_file" \
      --symmetric --cipher-algo AES256 --compress-algo none --output - \
  | split -d -a 4 -b "$chunk_bytes" - "$archive_prefix"

start_jumpserver

python3 - "$snapshot_dir" "$stamp" "$node_name" "$DB_NAME" <<'PY'
import hashlib
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

snapshot = Path(sys.argv[1])
parts = []
for path in sorted(snapshot.glob("*.part-*")):
    digest = hashlib.sha256()
    with path.open("rb") as source:
        while chunk := source.read(1024 * 1024):
            digest.update(chunk)
    parts.append({"name": path.name, "bytes": path.stat().st_size, "sha256": digest.hexdigest()})
if not parts:
    raise SystemExit("Encrypted backup has no archive parts")
manifest = {
    "formatVersion": 1,
    "createdAt": datetime.now(timezone.utc).isoformat().replace("+00:00", "Z"),
    "snapshot": sys.argv[2],
    "node": sys.argv[3],
    "database": sys.argv[4],
    "contents": [
        "WAO MySQL logical dump",
        "Jenkins consistent local archive",
        "JumpServer config and persistent data",
        "WAO deployment environment and certificates",
    ] + (["WAO private object bytes and per-object SHA-256 manifest"]
         if __import__("os").environ.get("WAO_STORAGE_MODE") == "s3" else []),
    "encryption": "GnuPG symmetric AES256",
    "archiveParts": parts,
}
(snapshot / "manifest.json").write_text(
    json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
)
PY

remote_root="$(sed -n 's/^WAO_BACKUP_REMOTE_ROOT=//p' "$webdav_config" | tail -n 1)"
remote_root="${remote_root:-WAO-backups}"
remote_root="${remote_root#/}"
remote_root="${remote_root%/}"
remote_node="$remote_root/$node_name"
remote_snapshot="$remote_node/$stamp"
webdav=(python3 "$webdav_client" --config "$webdav_config")
[[ "${WAO_BACKUP_ALLOW_INSECURE_HTTP:-false}" == true ]] && webdav+=(--allow-http)
"${webdav[@]}" ensure-dir "$remote_snapshot"
for part in "$snapshot_dir"/*.part-*; do
  "${webdav[@]}" upload "$part" "$remote_snapshot/$(basename "$part")"
done
# Upload the manifest last. Its presence is the remote commit marker.
"${webdav[@]}" upload "$snapshot_dir/manifest.json" "$remote_snapshot/manifest.json"
touch "$snapshot_dir/.uploaded"

cutoff="$(date -u -d "$remote_retention_days days ago" +%Y%m%dT%H%M%SZ)"
while IFS= read -r remote_entry; do
  [[ "$remote_entry" =~ ^[0-9]{8}T[0-9]{6}Z$ ]] || continue
  if [[ "$remote_entry" < "$cutoff" ]]; then
    "${webdav[@]}" delete "$remote_node/$remote_entry"
  fi
done < <("${webdav[@]}" list-dirs "$remote_node")

find "$local_root" -mindepth 1 -maxdepth 1 -type d -name '????????T??????Z' \
  -mtime "+$local_retention_days" -exec rm -rf -- {} +

printf 'Offsite backup uploaded and verified: %s/%s\n' "$node_name" "$stamp"
