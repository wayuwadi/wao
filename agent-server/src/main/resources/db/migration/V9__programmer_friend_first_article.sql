这句话让我意识到一件事。

现在每天都有新的 AI 模型、新工具和新玩法出现。对我来说，安装一个工具、看懂报错、把几个服务接起来，可能只是工作里很普通的一部分；但对很多朋友来说，光是从哪里开始，就已经很难了。

他们缺的往往不是又一篇罗列功能的教程，而是身边有一个程序员朋友：遇到问题时可以随时问一句，对方能听懂他的真实需求，把复杂的技术翻译成能照着完成的步骤，必要时还能直接帮他把东西做出来。

这也是我想做 WAO 的原因。

## 我最初想解决的，是自己的问题

我的很多事情原来散落在不同地方：突然冒出来的想法留在聊天窗口，准备做的事情放在任务软件，资料躺在网盘，做完后的经验又没有及时整理。过一段时间再回头，我经常只记得“当时做过”，却很难迅速找到为什么做、怎么做，以及最后得到了什么。

AI 很聪明，但如果它每次见到我都像第一次认识，它就只能回答眼前的一个问题，很难陪我把一件事持续做完。

所以我开始做 WAO。我希望它能把任务、知识、记忆、文件、聊天和 AI 行动慢慢接到一起：一个想法可以先被记住，需要行动时变成任务，执行过程留下记录，完成后的方法又沉淀成下一次可以使用的经验。

WAO 还在成长，它远没有到“什么都能做”的程度。但它已经越来越像一个属于我自己的工作和生活入口。

## 我也不想把自己包装成 AI 老师

AI 变化太快，没有人能永远站在讲台上告诉别人标准答案。我更愿意做朋友们的程序员朋友。

你不需要先学会一堆术语。你可以直接告诉我：

- 我想用 Codex 帮我改一个小程序，但不知道怎么开始；
- 我每天都在重复整理同一份表格，能不能让 AI 帮忙；
- 我有一个想法，能不能先做出一个真正可以打开的版本；
- 我看见一个新的 AI 工具，但不知道它跟我有什么关系。

我会尽量从问题本身出发，告诉你用了什么工具、为什么这样选、具体经过哪些步骤，以及最后的结果到底能不能用。成功的过程可以分享，踩过的坑也可以分享；暂时做不到的地方，就明确说还做不到。

## 接下来，我会在这里记录什么

第一类，是 WAO 自己的成长过程。从一个想法，到一个功能真正被做出来、测试、上线，再到我实际使用后的调整，我会把这个过程持续记录下来。

第二类，是 AI 相关的新资讯。我不会只转发“某个模型又刷新榜单”，而会多问一步：它对我们的工作和生活到底有什么影响，普通人现在能拿它做什么。

第三类，是我使用 AIGC 做出来的内容。图片、文章，以及以后可能出现的视频，我会把成品和背后的创作过程一起留下。

第四类，是工作和生活里的 AI 实战。每篇尽量讲清楚一个真实问题：我怎么拆解、用了哪些工具、输入了什么、遇到了什么问题，最后怎样落地。

目前先从图文开始。想到的话题统一放进 WAO，整理好一篇就发一篇。我不想先做一张看起来很宏大的更新计划，然后因为计划太大迟迟没有第一篇。

## 这些文章不一定是我逐字敲出来的

以后的很多内容，不会是我坐在空白文档前一个字一个字写出来的。它们可能从一次聊天开始，也可能来自我随手记下的几句话、WAO 里的某段记忆，或者知识库里以前整理过的资料。

AI 会参与整理和成稿，但我希望文章里的经历、判断和态度仍然属于我。

因此我也在 WAO 里慢慢搭建自己的内容工作台：它记得我的账号定位和表达方式，能结合我的想法、聊天、记忆、知识库和以前写过的内容生成草稿；我再检查、修改和确认。文章发布以后，平台、链接、发布时间以及后续的阅读和互动数据，也继续留在 WAO 里。

对我来说，这不只是“让 AI 帮我写文章”，而是在建立一条属于自己的内容生产通路。每一次聊天、修改和发布，都能成为下一篇内容更了解我的基础。

