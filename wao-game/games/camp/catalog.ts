export function waveRoster(
  map: number,
  wave: number,
  endless = false,
): (EnemyKind | BossKind)[] {
  const m = maps[map]!,
    cycle = (wave - 1) % 12,
    pattern = m.waves[cycle]!,
    count =
      7 +
      Math.floor(cycle * 0.6) +
      (endless ? Math.min(20, Math.floor(wave / 12) * 3) : 0);
  const list: (EnemyKind | BossKind)[] = Array.from(
    { length: count },
    (_, i) => pattern[i % pattern.length]!,
  );
  if (cycle === 11)
    list.splice(
      Math.floor(list.length / 2),
      0,
      endless ? maps[Math.floor((wave - 1) / 12) % 3]!.boss : m.boss,
    );
  return list;
}
