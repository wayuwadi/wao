import DOMPurify from 'dompurify'

/** Model-authored content remains inert and cannot load remote assets or navigate. */
export function recapDocument(html: string, dark = false): string {
  const clean = DOMPurify.sanitize(html, {
    WHOLE_DOCUMENT: true,
    ALLOWED_TAGS: [
      'html',
      'head',
      'body',
      'style',
      'main',
      'header',
      'footer',
      'section',
      'article',
      'aside',
      'div',
      'span',
      'p',
      'h1',
      'h2',
      'h3',
      'h4',
      'strong',
      'b',
      'em',
      'i',
      'small',
      'br',
      'hr',
      'ul',
      'ol',
      'li',
      'dl',
      'dt',
      'dd',
      'figure',
      'figcaption',
      'blockquote',
      'table',
      'thead',
      'tbody',
      'tr',
      'th',
      'td',
      'details',
      'summary',
      'svg',
      'g',
      'path',
      'line',
      'polyline',
      'polygon',
      'rect',
      'circle',
      'text',
    ],
    ALLOWED_ATTR: [
      'id',
      'class',
      'style',
      'role',
      'aria-label',
      'aria-hidden',
      'open',
      'colspan',
      'rowspan',
      'viewBox',
      'width',
      'height',
      'd',
      'x',
      'y',
      'x1',
      'y1',
      'x2',
      'y2',
      'cx',
      'cy',
      'r',
      'rx',
      'fill',
      'stroke',
      'stroke-width',
      'points',
      'transform',
      'text-anchor',
    ],
    ALLOW_DATA_ATTR: true,
  })
  const parsed = new DOMParser().parseFromString(clean, 'text/html')
  const styles = [...parsed.querySelectorAll('style')].map((el) => el.outerHTML).join('')
  parsed.querySelectorAll('style').forEach((el) => el.remove())
  return `<!doctype html><html lang="zh-CN"><head><meta charset="utf-8"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'unsafe-inline'; script-src 'none'; form-action 'none'; base-uri 'none'; img-src 'none'"><meta name="viewport" content="width=device-width,initial-scale=1">${styles}<style>
  :root{color-scheme:${dark ? 'dark' : 'light'};--page-bg:${dark ? '#111b19' : '#f3f6f4'};--surface:${dark ? '#192623' : '#fff'};--surface-2:${dark ? '#21332d' : '#ecf1ee'};--text:${dark ? '#e6ede9' : '#1a2521'};--muted:${dark ? '#a8bab1' : '#5d6c66'};--line:${dark ? '#3d5148' : '#dee6e1'};--accent:${dark ? '#7adcc0' : '#0b6b57'};--accent-soft:${dark ? '#203d32' : '#e2f0ea'}}
  *{box-sizing:border-box;min-width:0}html,body{margin:0;background:var(--page-bg);color:var(--text);font-family:system-ui,'Microsoft YaHei',sans-serif}body{line-height:1.75;overflow-wrap:anywhere}main{max-width:800px;margin:auto;padding:32px 24px}svg{max-width:100%;height:auto}table{display:block;max-width:100%;overflow:auto}pre{white-space:pre-wrap}h1{font-size:clamp(26px,5vw,36px);line-height:1.35}p{overflow-wrap:anywhere}summary{cursor:pointer;min-height:44px}
  @media(max-width:600px){main{padding:24px 16px!important}[data-grid]:not([data-keep-columns]){grid-template-columns:minmax(0,1fr)!important}[data-keep-columns]{grid-template-columns:repeat(2,minmax(0,1fr))!important}h1{font-size:28px!important}h2{font-size:21px!important}}
  </style></head><body>${parsed.body.innerHTML}</body></html>`
}
