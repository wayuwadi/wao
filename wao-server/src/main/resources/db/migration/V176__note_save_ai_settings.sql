CREATE TABLE IF NOT EXISTS note_ai_save_signal (
 doc_id VARCHAR(32) NOT NULL PRIMARY KEY,
 member_id VARCHAR(32) NOT NULL,
 user_generation BIGINT NOT NULL DEFAULT 1,
 cycle_id CHAR(32) NOT NULL,
 source_rev INT NOT NULL,
 title_origin VARCHAR(16) NOT NULL,
 last_title VARCHAR(256) NOT NULL,
 body_hash CHAR(64) NOT NULL,
 policy_json LONGTEXT NOT NULL,
 source_json LONGTEXT NOT NULL,
 cover_url VARCHAR(1000) NULL,
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 FOREIGN KEY(doc_id) REFERENCES doc(id) ON DELETE CASCADE,
 FOREIGN KEY(member_id) REFERENCES member(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS note_ai_stage_attempt (
 id CHAR(32) NOT NULL PRIMARY KEY,
 doc_id VARCHAR(32) NOT NULL,
 member_id VARCHAR(32) NOT NULL,
 cycle_id CHAR(32) NOT NULL,
 stage VARCHAR(16) NOT NULL,
 attempt_no INT NOT NULL,
 manual_stage BOOLEAN NOT NULL DEFAULT FALSE,
 cancel_epoch BIGINT NOT NULL DEFAULT 0,
 state VARCHAR(16) NOT NULL,
 reason_code VARCHAR(32) NULL,
 message VARCHAR(500) NULL,
 job_id VARCHAR(36) NULL,
 source_json LONGTEXT NOT NULL,
 input_text LONGTEXT NOT NULL,
 policy_json LONGTEXT NOT NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 UNIQUE KEY uk_note_stage_attempt(cycle_id,stage,attempt_no),
 KEY idx_note_attempt_member(member_id,state),
 KEY idx_note_attempt_doc(doc_id,cycle_id),
 FOREIGN KEY(doc_id) REFERENCES doc(id) ON DELETE CASCADE,
 FOREIGN KEY(member_id) REFERENCES member(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
