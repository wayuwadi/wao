CREATE TABLE note_ai_workflow (
    doc_id VARCHAR(32) NOT NULL,
    member_id VARCHAR(32) NOT NULL,
    base_rev INT NOT NULL,
    original_title VARCHAR(256) NOT NULL,
    source_markdown_hash CHAR(64) NOT NULL,
    title_status VARCHAR(16) NOT NULL,
    title_job_id VARCHAR(36) NULL,
    image_status VARCHAR(16) NOT NULL,
    image_run_id VARCHAR(32) NULL,
    polish_status VARCHAR(16) NOT NULL,
    polish_job_id VARCHAR(36) NULL,
    last_error VARCHAR(500) NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (doc_id),
    KEY idx_note_ai_workflow_member (member_id, updated_at),
    KEY idx_note_ai_workflow_pending (updated_at, title_status, image_status, polish_status),
    CONSTRAINT fk_note_ai_workflow_doc FOREIGN KEY (doc_id) REFERENCES doc(id) ON DELETE CASCADE,
    CONSTRAINT fk_note_ai_workflow_member FOREIGN KEY (member_id) REFERENCES member(id) ON DELETE CASCADE,
    CONSTRAINT chk_note_ai_title_status CHECK (title_status IN ('PENDING','RUNNING','DONE','FAILED','SKIPPED')),
    CONSTRAINT chk_note_ai_image_status CHECK (image_status IN ('PENDING','RUNNING','DONE','FAILED','SKIPPED')),
    CONSTRAINT chk_note_ai_polish_status CHECK (polish_status IN ('PENDING','RUNNING','DONE','FAILED','SKIPPED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='新建小记后台自动整理的逐阶段状态';

CREATE TABLE note_mining_visual (
    job_id VARCHAR(36) NOT NULL,
    member_id VARCHAR(32) NOT NULL,
    lens VARCHAR(16) NOT NULL,
    caption VARCHAR(500) NOT NULL,
    rationale VARCHAR(1000) NOT NULL,
    source_indexes_json JSON NOT NULL,
    image_run_id VARCHAR(32) NULL,
    image_url VARCHAR(1000) NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    error_message VARCHAR(500) NULL,
    feedback_status VARCHAR(16) NOT NULL DEFAULT 'CANDIDATE',
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (job_id, lens),
    KEY idx_note_mining_visual_member (member_id, created_at),
    CONSTRAINT fk_note_mining_visual_job FOREIGN KEY (job_id) REFERENCES note_mining_job(id) ON DELETE CASCADE,
    CONSTRAINT fk_note_mining_visual_member FOREIGN KEY (member_id) REFERENCES member(id) ON DELETE CASCADE,
    CONSTRAINT chk_note_mining_visual_lens CHECK (lens IN ('PROGRESS','REFRAME','NEXT_STEP')),
    CONSTRAINT chk_note_mining_visual_status CHECK (status IN ('PENDING','RUNNING','DONE','FAILED')),
    CONSTRAINT chk_note_mining_visual_feedback CHECK (feedback_status IN ('CANDIDATE','SAVED','NOT_ACCURATE'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='小记挖掘三视角图片候选';
